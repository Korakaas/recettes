import { emptyDraft, type Recipe } from '../types'

/** Quelques recettes d'exemple pour le mode démo. Les notes et dates sont fictives. */
function r(partial: Partial<Recipe> & { id: string; name: string }): Recipe {
  return { ...emptyDraft(), createdAt: 1, updatedAt: 1, ...partial }
}

const daysAgo = (n: number): string => {
  const d = new Date()
  d.setDate(d.getDate() - n)
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const day = String(d.getDate()).padStart(2, '0')
  return `${d.getFullYear()}-${m}-${day}`
}

